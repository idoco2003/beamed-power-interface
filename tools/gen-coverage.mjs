// Which requirements has anything ever executed?
//
// The number matters because 47 of 112 requirements had never been run by
// anything, and a claim that "the reference implementation covers BPI-S" is
// worth exactly as much as the evidence behind it. So this does not take the
// reference implementation's word for it: it RUNS the tests and reads the
// requirement ids out of the output. A test that is deleted, skipped or
// failing cannot contribute coverage, because its lines never appear.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const checklist = JSON.parse(readFileSync('conformance/checklist.json', 'utf8'));
const titleOf = new Map(checklist.requirements.map((r) => [r.id, r.text ?? r.title ?? '']));

let out;
try {
  out = execFileSync('node', ['reference/test-interlock.mjs'], { encoding: 'utf8' });
} catch (e) {
  // A failing suite must not silently publish yesterday's coverage.
  console.error('coverage: the interlock suite failed; refusing to write COVERAGE.md');
  process.stdout.write(e.stdout ?? '');
  process.exit(1);
}

// Only lines that actually passed count. A FAIL line names its requirement too,
// and counting it would let a broken implementation claim coverage.
const executed = new Map();
for (const line of out.split('\n')) {
  if (/\bFAIL\b/.test(line)) continue;
  for (const id of line.match(/R-[A-Z]+-\d+/g) ?? []) {
    executed.set(id, (executed.get(id) ?? 0) + 1);
  }
}

const vectors = JSON.parse(readFileSync('conformance/vectors/token-chain.json', 'utf8'));
for (const v of vectors.vectors ?? []) {
  // Vectors name one requirement each; accept a list too, in case they grow.
  const rs = v.requirements ?? (v.requirement ? [v.requirement] : []);
  for (const id of rs) executed.set(id, (executed.get(id) ?? 0) + 1);
}

const ids = [...executed.keys()].sort();
const byPart = {};
for (const id of ids) (byPart[id.split('-')[1]] ??= []).push(id);

const total = checklist.requirements.length;
const rows = ids.map((id) => `| \`${id}\` | ${executed.get(id)} | ${titleOf.get(id) ?? ''} |`).join('\n');

writeFileSync('reference/COVERAGE.md', `<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- GENERATED by tools/gen-coverage.mjs from a passing test run. Do not edit. -->

# Executed requirement coverage

**${ids.length} of ${total}** normative requirements are executed by something that runs.
Before the reference implementation existed the figure for BPI-S, BPI-RF and BPI-SEC was
**zero** — 47 requirements had never been run by anything at all.

By part: ${Object.entries(byPart).map(([p, v]) => `BPI-${p} ${v.length}`).join(' · ')}.

## What this table is not

Executed is not conformant. These assertions are the author's own, run against the
author's own implementation, and agreement between two things one person wrote is not
evidence of interoperability — see \`OBJECTIONS.md\` O-1. What the table establishes is
narrower and still worth having: that these requirements are **implementable as written**,
and that the behaviour they describe has been observed rather than only asserted.

Nothing here covers BPI-RF. Those 15 requirements are about radiated power and cannot be
executed without hardware.

| Requirement | Assertions | Text |
|---|---|---|
${rows}
`);

console.log(`coverage: ${ids.length}/${total} requirements executed`);
