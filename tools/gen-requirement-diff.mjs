//
// The requirement-set diff [G-1] promises.
//
//   "Each release SHALL publish a machine-readable changelog and a diff of the
//    normative requirement set -- which requirement identifiers were added,
//    changed in meaning, or withdrawn."
//
// Added and withdrawn are computable. CHANGED IN MEANING IS NOT. A tool can see
// that a requirement's text differs between two revisions; it cannot see whether
// the difference obliges an implementer to do something new. That judgement is
// the editor's, and pretending otherwise would produce a diff that says
// "changed" for a fixed typo and "changed" for a reversed SHALL in the same
// voice, which is worse than no diff at all.
//
// So this tool computes what it can, and REFUSES TO FINISH while any text change
// is unclassified. The classifications live in tools/requirement-diff-notes.json
// and are permanent: a release's diff must still be reproducible years later.
//
//   node tools/gen-requirement-diff.mjs <baseRef> [headRef]
//
// headRef defaults to the working tree.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const [baseRef, headRef] = process.argv.slice(2);
if (!baseRef) {
  console.error('usage: gen-requirement-diff.mjs <baseRef> [headRef]');
  process.exit(2);
}

const NOTES = 'tools/requirement-diff-notes.json';
const OUT_JSON = 'conformance/requirement-diff.json';
const OUT_MD = 'conformance/requirement-diff.md';

function checklistAt(ref) {
  const raw = ref
    ? execFileSync('git', ['show', `${ref}:conformance/checklist.json`], { encoding: 'utf8' })
    : readFileSync('conformance/checklist.json', 'utf8');
  const d = JSON.parse(raw);
  return {
    version: d.bpiVersion,
    byId: new Map(d.requirements.map((r) => [r.id, r])),
  };
}

const base = checklistAt(baseRef);
const head = checklistAt(headRef);

const added = [...head.byId.keys()].filter((id) => !base.byId.has(id)).sort();
const withdrawn = [...base.byId.keys()].filter((id) => !head.byId.has(id)).sort();
const textChanged = [...head.byId.keys()]
  .filter((id) => base.byId.has(id) && base.byId.get(id).summary !== head.byId.get(id).summary)
  .sort();

// Also worth surfacing: a requirement that moved between spec files. It is not a
// change in meaning, but it is a change an implementer tracking sections notices.
const moved = [...head.byId.keys()]
  .filter((id) => base.byId.has(id) && base.byId.get(id).source !== head.byId.get(id).source)
  .sort();

const notes = existsSync(NOTES) ? JSON.parse(readFileSync(NOTES, 'utf8')) : { classifications: {} };
const cls = notes.classifications ?? {};

// Keyed on the texts, not on the refs. A classification made while drafting must
// survive being re-run at release time against a tag, or the editor is asked the
// same question twice and the second answer is the one nobody thought about.
const short = (s) => createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 12);
const key = (id) => `${id}@${short(base.byId.get(id).summary)}->${short(head.byId.get(id).summary)}`;
const unclassified = textChanged.filter((id) => !cls[key(id)]);

if (unclassified.length) {
  console.error(`requirement-diff: ${unclassified.length} text change(s) are unclassified.`);
  console.error(`Add each to ${NOTES} under "classifications" as one of`);
  console.error('  "editorial"  — the obligation is unchanged');
  console.error('  "normative"  — an implementer must do something different');
  console.error('with a one-line "why". Suggested skeleton:\n');
  const skeleton = Object.fromEntries(
    unclassified.map((id) => [key(id), { change: 'editorial|normative', why: '' }]),
  );
  console.error(JSON.stringify({ classifications: skeleton }, null, 2));
  process.exit(1);
}

const normative = textChanged.filter((id) => cls[key(id)].change === 'normative');
const editorial = textChanged.filter((id) => cls[key(id)].change === 'editorial');

const diff = {
  $comment: 'SPDX-License-Identifier: CC-BY-4.0',
  about: '[G-1] requirement-set diff. Generated by tools/gen-requirement-diff.mjs.',
  from: { ref: baseRef, bpiVersion: base.version, count: base.byId.size },
  to: { ref: headRef ?? 'working tree', bpiVersion: head.version, count: head.byId.size },
  added: added.map((id) => ({ id, summary: head.byId.get(id).summary, source: head.byId.get(id).source })),
  withdrawn: withdrawn.map((id) => ({ id, summary: base.byId.get(id).summary })),
  changedInMeaning: normative.map((id) => ({
    id, why: cls[key(id)].why, was: base.byId.get(id).summary, now: head.byId.get(id).summary,
  })),
  editorialOnly: editorial.map((id) => ({ id, why: cls[key(id)].why })),
  moved: moved.map((id) => ({ id, from: base.byId.get(id).source, to: head.byId.get(id).source })),
};

writeFileSync(OUT_JSON, JSON.stringify(diff, null, 2) + '\n');

const section = (title, rows) =>
  `## ${title}\n\n${rows.length ? rows.join('\n') : '_None._'}\n\n`;

writeFileSync(OUT_MD, `<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- GENERATED by tools/gen-requirement-diff.mjs. Do not edit. -->

# Requirement-set diff

\`${diff.from.bpiVersion}\` (${baseRef}, ${diff.from.count} requirements) →
\`${diff.to.bpiVersion}\` (${headRef ?? 'working tree'}, ${diff.to.count} requirements)

${diff.from.bpiVersion === diff.to.bpiVersion && (diff.added.length || diff.withdrawn.length || normative.length)
  ? `> **The requirement set has changed and the version string has not.** Both sides say
> \`${diff.to.bpiVersion}\`. During a draft period that is expected — changes accumulate
> before a release bumps the version — but it means \`bpiVersion\` in a message does not
> currently distinguish these requirement sets, and an implementer cannot tell from the
> wire which one a peer built against. The version MUST be bumped before release.

`
  : ''}This is what [G-1] promises: which normative requirement identifiers were added,
changed in meaning, or withdrawn. **Whether a text change is a change in meaning is an
editor's judgement, recorded in \`tools/requirement-diff-notes.json\`, not something this
tool inferred.** An implementer who wants to check that judgement can read both texts
below and disagree.

${section('Added', diff.added.map((r) => `- **\`${r.id}\`** (${r.source}) — ${r.summary}`))}${section(
  'Withdrawn', diff.withdrawn.map((r) => `- **\`${r.id}\`** — was: ${r.summary}`))}${section(
  'Changed in meaning', diff.changedInMeaning.map((r) =>
    `### \`${r.id}\`\n\n${r.why}\n\n**Was:** ${r.was}\n\n**Now:** ${r.now}`))}${section(
  'Editorial only', diff.editorialOnly.map((r) => `- \`${r.id}\` — ${r.why}`))}${section(
  'Moved between sections', diff.moved.map((r) => `- \`${r.id}\` — ${r.from} → ${r.to}`))}`);

console.log(`requirement-diff: +${added.length} added, -${withdrawn.length} withdrawn, ` +
  `${normative.length} changed in meaning, ${editorial.length} editorial, ${moved.length} moved`);
